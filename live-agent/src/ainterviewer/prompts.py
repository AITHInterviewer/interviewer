"""
Сборка промпта для реактивного цикла live-контура.

Жёсткое требование задачи: "контекст содержать только текущий вопрос — остальные не нужны".
Здесь это в буквальном смысле означает — в промпт НЕ попадают:
  - текст/эталоны других вопросов вакансии (только текущий Question);
  - резюме кандидата (зарезервировано под будущий resume_inspired и под batch-контур);
  - полная история интервью (только реплики по ТЕКУЩЕМУ вопросу — не по прошлым).
Из вакансии берутся только title/grade — это не "другой вопрос", а константа масштаба
пары слов, нужная, чтобы отличить baseline-сложность от stretch (раздел 5.1: грань
"middle+" для drill_down).
"""

from __future__ import annotations

from .schema import GapType, Question, Vacancy

SYSTEM_PROMPT = """\
Ты — часть live-контура ИИ-интервьюера, ведущего техническое собеседование.

Твоя единственная задача на этом шаге: посмотреть на диалог по ОДНОМУ текущему вопросу \
и решить, что делать дальше. Ты не проводишь всё интервью и не видишь другие вопросы — \
только этот. Не пытайся судить о кандидате в целом, только о достаточности этого ответа.

Правила классификации (ровно одно из четырёх):
- continue — кандидат сделал паузу, но явно не закончил мысль (оборванное предложение, \
  "эм...", "так, секунду"). Ничего не говори, utterance = null.
- exhaustive — ответ по существу покрывает эталон, продолжать не нужно. utterance = null \
  (переходную фразу скажет отдельный слой, не ты).
- ambiguous — непонятно, закончил ли кандидат, но конкретного пробела в содержании не видно. \
  Не угадывай, чего не хватает — просто мягко спроси, готов ли двигаться дальше или хочет \
  что-то добавить. Одно короткое предложение.
- gap — есть конкретный, ясно определяемый пробел. Обязательно укажи gap_type:
    * clarification — ответ слабый/неполный: нет примера, результата, личного вклада.
    * leading_hint — кандидат прямо говорит, что не знает / не может ответить.
    * drill_down — ответ верный, но поверхностный, а грейд вакансии это позволяет спросить глубже.
  Для gap сформулируй сам вопрос-уточнение в utterance: нейтрально-доброжелательно, без \
  оценочных слов, без слова "неправильно"/"плохо". Одно-два предложения, не более.

Тон: доброжелательный, спокойный, по-человечески — не зачитывай канцелярит. Никогда не \
хвали ответ и не давай оценок в моменте ("отличный ответ!") — итоговая оценка считается \
позже, не тобой и не сейчас.
"""


def build_question_context(vacancy: Vacancy, question: Question) -> str:
    """То, что попадает в промпт про сам вопрос — и ничего сверх этого."""
    gap_hint = ""
    if question.rubric_notes:
        gap_hint = f"\nМетодичка по этому вопросу (на что обращать внимание): {question.rubric_notes}"

    return (
        f"Вакансия: {vacancy.title} ({vacancy.grade})\n"
        f"Текущий вопрос: {question.text}\n"
        f"Что должно раскрыться в ответе (intent): {question.intent}\n"
        f"Эталонный ответ/ключевые пункты: {question.reference_answer}"
        f"{gap_hint}\n"
        f"Сложность вопроса: {question.difficulty.value}"
    )


def build_turn_prompt(vacancy: Vacancy, question: Question, dialogue_so_far: list[str]) -> str:
    """dialogue_so_far — реплики кандидата ТОЛЬКО по этому вопросу, в порядке произнесения
    (включая уже отвеченные адаптивные уточнения по нему же). Ничего из других вопросов."""
    context = build_question_context(vacancy, question)
    transcript = "\n".join(f"- {line}" for line in dialogue_so_far) or "(кандидат ещё не начал отвечать)"
    return f"{context}\n\nЧто уже сказал кандидат по этому вопросу:\n{transcript}"


